# operações matemáticas

a = {1, 2, 3}
b = {3, 4, 5}

#operação de união = junção dos dois conjuntos sem trazer os elementos repetidos
print(a | b)

# operação de intercerção - trazer os elementos que tem em comum entre os dois conjutos
print(a & b)

# operação de diferença - traz os elementos que são exclusivos do conjunto a
print (a - b) # a posição importa